#!/usr/bin/env bash
set -euo pipefail

target_dir="${TARGET_DIR:-${1:-}}"
authorized_keys_file="${SOCKIT_AUTHORIZED_KEYS_FILE:-}"

if [[ -z "$target_dir" ]]; then
    echo "post-build.sh: missing TARGET_DIR" >&2
    exit 1
fi

# 1) Authorized SSH key.  SSH key is the ONLY way into a deployed board
# — root password is locked below, so without an authorized key you have
# to reflash the SD to recover.
if [[ -n "$authorized_keys_file" ]]; then
    if [[ ! -f "$authorized_keys_file" ]]; then
        echo "post-build.sh: missing SOCKIT_AUTHORIZED_KEYS_FILE: $authorized_keys_file" >&2
        exit 1
    fi
    install -d -m 700 "$target_dir/root/.ssh"
    install -m 600 "$authorized_keys_file" "$target_dir/root/.ssh/authorized_keys"
    echo "Installed root authorized_keys from: $authorized_keys_file"
fi

# 2) Lock root in /etc/shadow.  BR2_TARGET_GENERIC_ROOT_PASSWD takes
# plaintext, so it can't be used to set the conventional locked marker
# "!" — we'd just be setting "!" as the literal password.  Rewrite the
# password field directly here, after buildroot has assembled shadow.
shadow="$target_dir/etc/shadow"
if [[ -f "$shadow" ]]; then
    tmp="$(mktemp)"
    awk -F: '
        BEGIN { OFS=":" }
        $1 == "root" { $2 = "!" }
        { print }
    ' "$shadow" > "$tmp"
    install -m 600 "$tmp" "$shadow"
    rm -f "$tmp"
    echo "Locked root password in $shadow (no password can ever match)"
fi

# 3) Hardened sshd_config — make the secure defaults explicit so a
# careless edit to the upstream config doesn't quietly weaken auth.
sshd_config="$target_dir/etc/ssh/sshd_config"
if [[ -f "$sshd_config" ]]; then
    cat > "$sshd_config" <<'SSHD_EOF'
# Generated by sockit-linux post-build.sh.  Edits here are overwritten
# on the next build.  See package/openssh upstream defaults for any
# option not set explicitly.

Port 22
Protocol 2

# Auth — key-only.  Empty passwords disabled, password auth disabled,
# root only via key.
PermitRootLogin prohibit-password
PasswordAuthentication no
PermitEmptyPasswords no
PubkeyAuthentication yes
ChallengeResponseAuthentication no
KbdInteractiveAuthentication no
UsePAM no

# Tunables.  ClientAlive keeps long-running ssh sessions (e.g. during
# bringup) from being silently dropped by NAT.
ClientAliveInterval 60
ClientAliveCountMax 3
LoginGraceTime 30
MaxAuthTries 3
MaxSessions 10

# Listen on whatever address eth0 ends up at — the iptables firewall
# (S38ids_firewall) limits which subnets actually reach this listener.
ListenAddress 0.0.0.0

Subsystem sftp /usr/libexec/sftp-server
SSHD_EOF
    echo "Installed hardened sshd_config (key-only, password auth disabled)"
fi
